/**
 * The service worker's source, written into the build by vite.config.ts (Stage 7.5).
 *
 * - The game's code, styles, page, manifest and icons are stored when the worker installs,
 *   so the game opens offline after the first visit.
 * - Everything else (the page, models, textures, sounds) comes from the network when there
 *   is one, so a changed file shows at once, and is kept for when there is none.
 *   The browser's own cache keeps that cheap.
 * - Each build has its own store. A new build's worker waits until the game says "Reload"
 *   (see register.ts), then takes over and the old store is cleared.
 */
export function serviceWorkerSource(build: string, files: readonly string[]): string {
  return `// Season Ticket service worker, build ${build}. Generated by vite.config.ts.
const STORE = 'st-${build}';
const CORE = ${JSON.stringify(['./', ...files])};
const CORE_URLS = new Set(CORE.map((f) => new URL(f, self.registration.scope).pathname));

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(STORE).then((c) => c.addAll(CORE)));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('st-') && k !== STORE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('message', (e) => {
  if (e.data === 'skip-waiting') self.skipWaiting();
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(new URL(self.registration.scope).pathname)) return;
  const core = CORE_URLS.has(url.pathname);
  e.respondWith(
    caches.open(STORE).then(async (c) => {
      // The built code has a hash in every name: the stored copy is always right.
      if (core && req.mode !== 'navigate') {
        const hit = await c.match(req);
        if (hit) return hit;
      }
      try {
        const res = await fetch(req);
        if (res.status === 200 && res.type === 'basic' && req.mode !== 'navigate') c.put(req, res.clone()).catch(() => {});
        return res;
      } catch (err) {
        const hit = await c.match(req.mode === 'navigate' ? './' : req);
        if (hit) return hit;
        throw err;
      }
    }),
  );
});
`;
}

/** The built files the worker stores on install: everything but the big scene assets. */
export function coreFiles(names: readonly string[]): string[] {
  return names.filter((n) => /\.(js|css|html|webmanifest|png|svg)$/.test(n) && !n.startsWith('assets/office/') && !n.startsWith('assets/match/') && !n.startsWith('assets/audio/')).sort();
}
